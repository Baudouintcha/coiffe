<script>
// Toggle du chat
function iaToggleChat() {
    const chatWindow = document.getElementById('ia-chat-window');
    const orb = document.getElementById('ia-orb');
    chatWindow.classList.toggle('ia-chat-open');
    if (chatWindow.classList.contains('ia-chat-open')) {
        document.getElementById('ia-user-input').focus();
    }
}

// Envoyer un message
function iaSendMessage() {
    const input = document.getElementById('ia-user-input');
    const message = input.value.trim();
    if (!message) return;
    
    // Afficher le message utilisateur
    const chatContent = document.getElementById('ia-chat-content');
    const userMsg = document.createElement('div');
    userMsg.className = 'ia-message ia-message-user';
    userMsg.textContent = message;
    chatContent.appendChild(userMsg);
    
    input.value = '';
    chatContent.scrollTop = chatContent.scrollHeight;
    
    // Changer l'état de l'orbe
    const orb = document.getElementById('ia-orb');
    orb.className = 'ia-orb ia-state-listening';
    document.getElementById('ia-status-text').textContent = 'Écoute...';
    
    // Simuler la réflexion
    setTimeout(() => {
        orb.className = 'ia-orb ia-state-thinking';
        document.getElementById('ia-status-text').textContent = 'Réflexion...';
    }, 800);
    
    // Simuler une réponse (appel API)
    setTimeout(() => {
        orb.className = 'ia-orb ia-state-responding';
        document.getElementById('ia-status-text').textContent = 'En ligne';
        
        const aiMsg = document.createElement('div');
        aiMsg.className = 'ia-message ia-message-ai';
        aiMsg.textContent = 'Réponse de ' + message.substring(0, 20) + '...';
        chatContent.appendChild(aiMsg);
        chatContent.scrollTop = chatContent.scrollHeight;
        
        setTimeout(() => {
            orb.className = 'ia-orb ia-state-inactive';
        }, 2000);
    }, 2500);
}

// Suggestion rapide
function iaSendQuick(message) {
    document.getElementById('ia-user-input').value = message;
    iaSendMessage();
}

// Reconnaissance vocale
document.getElementById('ia-voice-btn')?.addEventListener('click', function() {
    const recognition = new (window.SpeechRecognition || window.webkitSpeechRecognition)();
    recognition.start();
    recognition.onresult = (event) => {
        let transcript = '';
        for (let i = event.resultIndex; i < event.results.length; i++) {
            transcript += event.results[i][0].transcript;
        }
        document.getElementById('ia-user-input').value = transcript;
    };
});
</script>

